export const DEFAULT_DISTRICT_ID = 'academic';

export function getDistrict(id) {
  return DISTRICTS.find((d) => d.id === id) || DISTRICTS[0];
}

export function getDistrictUpgrades(districtId = 'academic') {
  const d = getDistrict(districtId);
  return d.upgrades || [];
}

export function getNextDistrictUpgrade(districtId, currentStage = 0) {
  const upgrades = getDistrictUpgrades(districtId);
  const stage = typeof currentStage === 'number' ? Math.max(0, Math.floor(currentStage)) : 0;
  return stage < upgrades.length ? upgrades[stage] : null;
}

