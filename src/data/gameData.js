/**
 * Returns a balanced, rotating set of 5 daily quests for any given day offset.
 * Always delivers 1 Energy, 1 Waste, 1 Water, 1 Transit, 1 Food/Bio/Sector.
 */
export function getDailyQuests(dayOffset = 0) {
  const energyPool = DAILY_QUEST_POOL.filter((q) => q.category === 'Energy');
  const wastePool = DAILY_QUEST_POOL.filter((q) => q.category === 'Waste');
  const waterPool = DAILY_QUEST_POOL.filter((q) => q.category === 'Water');
  const transitPool = DAILY_QUEST_POOL.filter((q) => q.category === 'Transit');
  const otherPool = [
    ...DAILY_QUEST_POOL.filter((q) => ['Biodiversity', 'Food', 'Digital'].includes(q.category)),
    ...SECTOR_QUESTS,
  ];

  const offset = Math.max(0, Math.floor(Number(dayOffset) || 0));

  return [
    energyPool[offset % energyPool.length],
    wastePool[(offset + 1) % wastePool.length],
    waterPool[(offset + 2) % waterPool.length],
    transitPool[(offset + 3) % transitPool.length],
    otherPool[(offset + 4) % otherPool.length],
  ];
}

